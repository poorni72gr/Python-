marks = int(input("enter your marks :"))
if marks <35:
    print("fail")
elif marks >=35 and marks <50:
    print("c grade")
elif marks >=50 and marks <70:
    print("b grade")
elif marks >=70 and marks <80:
    print("a grade")
elif marks >=80 and marks <100:
    print("a+ grade")
else:
      print("invalid marks")
